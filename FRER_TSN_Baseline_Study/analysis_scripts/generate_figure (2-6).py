def parse_histograms(text):
    pattern = r'\[?([\d\.E\-]+)\s*[,:-]\s*([\d\.E\-]+)\s*\)?[^\d]*(\d+)'
    matches = re.findall(pattern, text)
    values = []
    for low, high, count in matches:
        try:
            l = float(low)
            h = float(high)
            c = int(count)
            if c > 0 and h > l:
                values.extend([(l + h) / 2.0] * c)
        except:
            continue
    return np.array(values)

