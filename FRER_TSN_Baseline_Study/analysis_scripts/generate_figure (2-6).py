def parse_table(text):
    lines = [ln.strip() for ln in text.strip().split('\n') if ln.strip()]
    rows = []
    for line in lines[1:]:
        parts = line.split()
        if len(parts) >= 18:
            rows.append([int(parts[0]), parts[1], int(parts[2]), int(parts[3]), int(parts[4]),
                         float(parts[5]), float(parts[6]), int(parts[7]), int(parts[8]),
                         int(parts[9]), int(parts[10]), float(parts[11]), float(parts[12]),
                         float(parts[13]), float(parts[14]), float(parts[15]), float(parts[16]),
                         float(parts[17])])
